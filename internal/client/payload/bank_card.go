// Package payload содержит структуры полезной нагрузки клиентских данных.
//
// Пакет описывает форматы данных, которые сериализуются в JSON,
// шифруются на стороне клиента и сохраняются в хранилище.
package payload

// BankCard описывает полезную нагрузку записи с банковской картой.
//
// Структура используется для хранения номера карты, имени держателя,
// срока действия и CVV-кода.
type BankCard struct {
	// Number содержит номер банковской карты.
	Number string `json:"number"`
	// Holder содержит имя держателя карты.
	Holder string `json:"holder"`
	// Expiry содержит срок действия карты.
	Expiry string `json:"expiry"`
	// CVV содержит CVV/CVC-код карты.
	CVV string `json:"cvv"`
}
