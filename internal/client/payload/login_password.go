// Package payload содержит структуры полезной нагрузки клиентских данных.
//
// Структуры пакета используются для сериализации пользовательских данных
// перед шифрованием и сохранением.
package payload

// LoginPassword описывает полезную нагрузку записи с логином и паролем.
//
// Структура используется для хранения пары логин/пароль.
type LoginPassword struct {
	// Login содержит логин пользователя.
	Login string `json:"login"`
	// Password содержит пароль пользователя.
	Password string `json:"password"`
}
